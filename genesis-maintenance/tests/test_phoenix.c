#include <assert.h>
#include <limits.h>
#include <stdio.h>
#include <string.h>
#include "../src/merc.h"

extern void init_mm(void);

static void recover(CHAR_DATA *ch)
{
    affect_strip(ch, gsn_phoenix_recovery);
    ch->wait = 0;
}

int main(void)
{
    CHAR_DATA actor, target;
    PC_DATA pc, other_pc;
    ROOM_INDEX_DATA room, home;
    AREA_DATA area;
    MOB_INDEX_DATA mob;
    AFFECT_DATA shared;
    OBJ_DATA flying_gear;
    long i, mana, hp, exp;
    char oversized[MAX_INPUT_LENGTH + 20];
    memset(&actor, 0, sizeof(actor));
    memset(&target, 0, sizeof(target));
    memset(&pc, 0, sizeof(pc));
    memset(&other_pc, 0, sizeof(other_pc));
    memset(&room, 0, sizeof(room));
    memset(&home, 0, sizeof(home));
    memset(&area, 0, sizeof(area));
    memset(&mob, 0, sizeof(mob));
    init_mm();
    for (i = 0; i < MAX_SKILL && skill_table[i].name != NULL; ++i)
        if (skill_table[i].pgsn != NULL) *skill_table[i].pgsn = i;
    actor.pcdata = &pc; target.pcdata = &other_pc;
    actor.name = "Actor"; target.name = "Target";
    actor.short_descr = "the actor"; target.short_descr = "the target";
    actor.morph = target.morph = "";
    actor.in_room = target.in_room = &room;
    room.area = home.area = &area;
    area.nplayer = 2;
    room.people = &actor; actor.next_in_room = &target;
    actor.position = target.position = POS_STANDING;
    actor.level = LEV_AWA; target.level = LEV_AWA;
    actor.hit = actor.max_hit = target.hit = target.max_hit = 100000;
    actor.mana = actor.max_mana = 100000;
    for (i = 0; i < 5; ++i) actor.stats[i] = target.stats[i] = 5;
    actor.style[0] = target.style[0] = STYLE_UNARMED;
    assert(phoenix_rank(&actor) == 0);
    do_autoclass(&actor, "phoenix");
    assert(actor.class == CLASS_PHOENIX && pc.powers[0] == 0);
    assert(stat_max(&actor, STAT_STR) == 9);
    assert(stat_max(&actor, STAT_DEX) == 8);
    assert(stat_max(&actor, STAT_CON) == 9);
    assert(stat_max(&actor, STAT_INT) == 10);
    assert(stat_max(&actor, STAT_WIS) == 11);
    actor.exp = 49999;
    do_phoenix(&actor, "train");
    assert(pc.powers[0] == 0 && actor.exp == 49999);
    actor.exp = 50000;
    do_phoenix(&actor, "train");
    assert(pc.powers[0] == 1 && actor.exp == 0);
    mana = actor.mana;
    do_phoenix(&actor, "ward");
    assert(actor.mana == mana && !is_affected(&actor, gsn_phoenix_ward));
    pc.powers[0] = 8;
    actor.exp = 99999999; exp = actor.exp;
    do_phoenix(&actor, "train");
    assert(pc.powers[0] == 8 && actor.exp == exp);
    pc.powers[0] = LONG_MAX; assert(phoenix_rank(&actor) == 8);
    pc.powers[0] = LONG_MIN; assert(phoenix_rank(&actor) == 0);
    pc.powers[0] = 8;
    puts("Phoenix selection, independent caps, bounded mastery and atomic training passed");

    actor.mana = 749; mana = actor.mana;
    do_phoenix(&actor, "ward");
    assert(actor.mana == mana && actor.armor == 0);
    actor.mana = 100000;
    do_phoenix(&actor, "ward");
    assert(actor.mana == 99250 && actor.armor == 20);
    assert(is_affected(&actor, gsn_phoenix_recovery));
    mana = actor.mana;
    do_phoenix(&actor, "ward");
    assert(actor.mana == mana && actor.armor == 20);
    recover(&actor);
    do_phoenix(&actor, "ward");
    assert(actor.mana == mana && actor.armor == 20);
    affect_strip(&actor, gsn_phoenix_ward);
    assert(actor.armor == 0);
    do_phoenix(&actor, "wings");
    assert(IS_AFFECTED(&actor, AFF_FLYING));
    affect_strip(&actor, gsn_phoenix_wings);
    assert(!IS_AFFECTED(&actor, AFF_FLYING));
    recover(&actor);
    do_phoenix(&actor, "wings");
    memset(&shared, 0, sizeof(shared));
    shared.type = skill_lookup("fly");
    shared.duration = 3;
    shared.bitvector = AFF_FLYING;
    affect_to_char(&actor, &shared);
    affect_strip(&actor, shared.type);
    assert(IS_AFFECTED(&actor, AFF_FLYING));
    affect_to_char(&actor, &shared);
    affect_strip(&actor, gsn_phoenix_wings);
    assert(IS_AFFECTED(&actor, AFF_FLYING));
    affect_strip(&actor, shared.type);
    assert(!IS_AFFECTED(&actor, AFF_FLYING));
    recover(&actor);
    do_phoenix(&actor, "wings");
    memset(&flying_gear, 0, sizeof(flying_gear));
    flying_gear.item_type = ITEM_ARMOR;
    flying_gear.value[3] = 3;
    flying_gear.wear_loc = 1;
    actor.carrying = &flying_gear;
    affect_strip(&actor, gsn_phoenix_wings);
    assert(IS_AFFECTED(&actor, AFF_FLYING));
    actor.carrying = NULL;
    REMOVE_BIT(actor.affected_by, AFF_FLYING);
    recover(&actor);
    SET_BIT(actor.affected_by, AFF_FLYING);
    mana = actor.mana;
    do_phoenix(&actor, "wings");
    assert(actor.mana == mana && !is_affected(&actor, gsn_phoenix_wings));
    REMOVE_BIT(actor.affected_by, AFF_FLYING);
    do_phoenix(&actor, "ascend");
    assert(actor.hitroll == 10 && actor.damroll == 10);
    recover(&actor);
    mana = actor.mana;
    do_phoenix(&actor, "ascend");
    assert(actor.hitroll == 10 && actor.damroll == 10 && actor.mana == mana);
    affect_strip(&actor, gsn_phoenix_ascend);
    assert(actor.hitroll == 0 && actor.damroll == 0);
    puts("Phoenix ward sign, flight ownership, ascendant nonstacking/removal and costs passed");

    actor.hit = actor.max_hit - 10;
    mana = actor.mana;
    do_phoenix(&actor, "tears");
    assert(actor.hit == actor.max_hit && actor.mana == mana - 1000);
    recover(&actor);
    mana = actor.mana;
    do_phoenix(&actor, "tears");
    assert(actor.mana == mana);
    target.hit = 100;
    do_phoenix(&actor, "tears Target");
    assert(target.hit == 100 && actor.mana == mana);
    target.leader = &actor;
    do_phoenix(&actor, "tears Target");
    assert(target.hit == 3100 && actor.mana == mana - 1000);
    recover(&actor);
    target.hit = 0;
    mana = actor.mana;
    do_phoenix(&actor, "tears Target");
    assert(target.hit == 0 && actor.mana == mana);
    actor.hit = 100;
    actor.fight_timer = 1;
    do_phoenix(&actor, "renew");
    assert(actor.hit == 100 && actor.mana == mana);
    actor.fight_timer = 0;
    do_phoenix(&actor, "renew");
    assert(actor.hit == 6100 && actor.mana == mana - 2000);
    recover(&actor);
    actor.home = -1; mana = actor.mana;
    do_phoenix(&actor, "ashwalk");
    assert(actor.in_room == &room && actor.mana == mana);
    home.vnum = 990003;
    home.name = "Phoenix Home";
    home.description = "A quiet testing home.\n\r";
    home.next = room_index_hash[home.vnum % MAX_KEY_HASH];
    room_index_hash[home.vnum % MAX_KEY_HASH] = &home;
    actor.home = home.vnum;
    room.room_flags = ROOM_NO_TELEPORT;
    do_phoenix(&actor, "ashwalk");
    assert(actor.in_room == &room && actor.mana == mana);
    room.room_flags = 0;
    home.room_flags = ROOM_PRIVATE;
    do_phoenix(&actor, "ashwalk");
    assert(actor.in_room == &room && actor.mana == mana);
    home.room_flags = 0;
    do_phoenix(&actor, "ashwalk");
    assert(actor.in_room == &home && actor.mana == mana - 1500);
    assert(is_affected(&actor, gsn_phoenix_recovery));
    char_from_room(&actor);
    char_to_room(&actor, &room);
    recover(&actor);
    room_index_hash[home.vnum % MAX_KEY_HASH] = home.next;
    puts("Phoenix healing caps, group-only support, no resurrection and failed-travel atomicity passed");

    actor.hit = actor.max_hit;
    target.hit = target.max_hit; target.leader = NULL;
    mana = actor.mana; hp = target.hit;
    room.room_flags = ROOM_SAFE;
    do_phoenix(&actor, "ember Target");
    assert(actor.mana == mana && target.hit == hp);
    room.room_flags = 0;
    do_phoenix(&actor, "ember Target");
    assert(actor.mana == mana && target.hit == hp);
    target.act = ACT_IS_NPC; target.pIndexData = &mob;
    do_phoenix(&actor, "ember Target");
    assert(actor.mana == mana - 500 && target.hit < hp);
    recover(&actor);
    mana = actor.mana; hp = target.hit;
    do_phoenix(&actor, "flare Target");
    assert(actor.mana == mana - 1500 && target.hit < hp);
    stop_fighting(&actor, TRUE);
    affect_strip(&target, gsn_blindness);
    puts("Phoenix attack pipeline, protected-target rejection and exact costs passed");

    phoenix_clear(&actor);
    actor.position = POS_STANDING;
    actor.fight_timer = 0;
    actor.mana = 100000;
    do_phoenix(&actor, "ward");
    recover(&actor);
    do_phoenix(&actor, "wings");
    recover(&actor);
    do_phoenix(&actor, "ascend");
    phoenix_clear(&actor);
    assert(actor.armor == 0 && actor.hitroll == 0 && actor.damroll == 0);
    assert(!IS_AFFECTED(&actor, AFF_FLYING));
    mana = actor.mana;
    memset(oversized, 'a', sizeof(oversized) - 1);
    oversized[sizeof(oversized) - 1] = '\0';
    do_phoenix(&actor, oversized);
    do_phoenix(&actor, NULL);
    do_phoenix(&actor, "ward Target");
    do_phoenix(&actor, "notapower");
    assert(actor.mana == mana);
    actor.class = CLASS_ELEM;
    pc.powers[ELEM_FIRE] = 10;
    memset(&shared, 0, sizeof(shared));
    shared.type = gsn_lycaon;
    shared.duration = 1;
    affect_to_char(&actor, &shared);
    do_phoenix(&actor, "");
    assert(actor.mana == mana && !IS_POLYAFF(&actor, POLY_PHOENIXFORM));
    affect_strip(&actor, gsn_lycaon);
    actor.class = CLASS_VAMPIRE;
    do_phoenix(&actor, "ward");
    assert(actor.mana == mana && !is_affected(&actor, gsn_phoenix_ward));
    puts("Phoenix cleanup, wrong-class, malformed-input and target arity checks passed");
    return 0;
}
